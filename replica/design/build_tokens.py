#!/usr/bin/env python3
"""Generate tokens.css and tailwind.preset.js from tokens.json + tokens.light.json.

    python3 replica/design/build_tokens.py

Dark is the default (:root). Light applies with [data-theme="light"] on <html> or any subtree,
or with the OS preference when <html> has no data-theme. [data-theme="dark"] forces dark. Re-run after every token
change, then run contrast.py on both files.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return json.load(fh)


def colour_vars(tokens, indent="  "):
    return "\n".join("%s--color-%s: %s;" % (indent, k, v) for k, v in tokens["color"].items())


def shadow_vars(tokens, indent="  "):
    return "\n".join("%s--shadow-%s: %s;" % (indent, k, v) for k, v in tokens["shadow"].items())


def static_vars(tokens):
    lines = []
    for k, v in tokens["font"].items():
        lines.append("  --font-%s: %s;" % (k, v))
    for k, v in tokens["type"].items():
        lines.append("  --text-%s: %spx;" % (k, v["size"]))
        lines.append("  --leading-%s: %spx;" % (k, v["line"]))
        lines.append("  --weight-%s: %s;" % (k, v["weight"]))
    for i, v in enumerate(tokens["space"]):
        lines.append("  --space-%d: %spx;" % (i, v))
    for k, v in tokens["size"].items():
        lines.append("  --size-%s: %spx;" % (k, v))
    for k, v in tokens["radius"].items():
        lines.append("  --radius-%s: %spx;" % (k, v))
    for k, v in tokens["motion"].items():
        lines.append("  --motion-%s: %s;" % (k, v))
    return "\n".join(lines)


def css(dark, light):
    return """/* Generated by build_tokens.py from tokens.json and tokens.light.json. Do not edit. */
:root {
  color-scheme: dark;
%s
%s
%s
}

:root[data-theme="light"], [data-theme="light"] {
  color-scheme: light;
%s
%s
}

[data-theme="dark"] {
  color-scheme: dark;
%s
%s
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
%s
%s
  }
}

@media (prefers-reduced-motion: reduce) {
  :root { --motion-fast: 0ms; --motion-base: 0ms; }
}
""" % (
        colour_vars(dark), shadow_vars(dark), static_vars(dark),
        colour_vars(light), shadow_vars(light),
        colour_vars(dark), shadow_vars(dark),
        colour_vars(light, "    "), shadow_vars(light, "    "),
    )


def preset(tokens):
    colours = {k: "var(--color-%s)" % k for k in tokens["color"]}
    font_size = {k: ["var(--text-%s)" % k, {"lineHeight": "var(--leading-%s)" % k}] for k in tokens["type"]}
    # Keys are the pixel values (p-12 = 12px), values point at the token variables.
    spacing = {str(v): "var(--space-%d)" % i for i, v in enumerate(tokens["space"])}
    spacing.update({k: "var(--size-%s)" % k for k in tokens["size"]})
    radius = {k: "var(--radius-%s)" % k for k in tokens["radius"]}
    shadow = {k: "var(--shadow-%s)" % k for k in tokens["shadow"]}
    theme = {
        "colors": dict(colours, transparent="transparent", current="currentColor"),
        "fontFamily": {"sans": "var(--font-sans)", "mono": "var(--font-mono)"},
        "fontSize": font_size,
        "spacing": spacing,
        "maxWidth": {k: "var(--size-%s)" % k for k in tokens["size"]},
        "borderRadius": dict(radius, none="0"),
        "boxShadow": dict(shadow, none="none"),
        "transitionDuration": {"fast": "var(--motion-fast)", "base": "var(--motion-base)"},
        "transitionTimingFunction": {"DEFAULT": "var(--motion-ease)"},
    }
    return (
        "// Generated by build_tokens.py. Do not edit.\n"
        "// Use as a preset: presets: [require('./replica/design/tailwind.preset.js')]\n"
        "// Components use roles (bg-surface, text-text-muted, border-border-input), never raw hex.\n"
        "/** @type {import('tailwindcss').Config} */\n"
        "module.exports = { darkMode: ['selector', '[data-theme=\"dark\"]'], theme: %s };\n"
        % json.dumps(theme, indent=2)
    )


def main():
    dark, light = load("tokens.json"), load("tokens.light.json")
    if set(dark["color"]) != set(light["color"]):
        raise SystemExit("colour roles differ between themes: %s" % (set(dark["color"]) ^ set(light["color"])))
    with open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8") as fh:
        fh.write(css(dark, light))
    with open(os.path.join(HERE, "tailwind.preset.js"), "w", encoding="utf-8") as fh:
        fh.write(preset(dark))
    print("wrote tokens.css and tailwind.preset.js (%d colour roles)" % len(dark["color"]))


if __name__ == "__main__":
    main()
